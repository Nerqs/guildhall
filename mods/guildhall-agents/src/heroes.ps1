param([Parameter(Mandatory = $true)][string]$Pack)
# Extracts every character of the Ninja Adventure Asset Pack (CC0, by pixel-boy) into
# ../heroes/<name>/ (name = the pack folder, lower case), upscaled 4x with nearest-neighbor:
#   face.png (38px portrait), idle.png (facing down), look-l.png / look-r.png (facing left/right),
#   walk1.png / walk3.png (two steps, facing down), item.png (arms up), dead.png (lying down).
#   powershell -NoProfile -ExecutionPolicy Bypass -File heroes.ps1 -Pack "<...>\Ninja Adventure - Asset Pack"
Add-Type -AssemblyName System.Drawing
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$out = Join-Path (Split-Path -Parent $here) "heroes"
$chars = Join-Path $Pack "Actor\Character"

function Crop($src, $dst, $x, $y, $w, $h) {
  if (-not (Test-Path $src)) { return }
  $img = [System.Drawing.Image]::FromFile($src)
  try {
    if ($x + $w -gt $img.Width -or $y + $h -gt $img.Height) { return }
    $bmp = New-Object System.Drawing.Bitmap ($w * 4), ($h * 4)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::NearestNeighbor
    $g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::Half
    $g.CompositingMode = [System.Drawing.Drawing2D.CompositingMode]::SourceCopy
    $g.DrawImage($img, (New-Object System.Drawing.Rectangle 0, 0, ($w * 4), ($h * 4)), $x, $y, $w, $h, [System.Drawing.GraphicsUnit]::Pixel)
    $g.Dispose(); $bmp.Save($dst, [System.Drawing.Imaging.ImageFormat]::Png); $bmp.Dispose()
  } finally { $img.Dispose() }
}

$names = @()
foreach ($d in Get-ChildItem $chars -Directory) {
  $a = Join-Path $d.FullName "SeparateAnim"
  if (-not (Test-Path (Join-Path $d.FullName "Faceset.png")) -or -not (Test-Path (Join-Path $a "Walk.png"))) { continue }
  $n = $d.Name.ToLower()
  $dst = Join-Path $out $n
  New-Item -ItemType Directory -Force $dst | Out-Null
  Crop (Join-Path $d.FullName "Faceset.png") (Join-Path $dst "face.png") 0 0 38 38
  Crop (Join-Path $a "Idle.png") (Join-Path $dst "idle.png") 0 0 16 16
  Crop (Join-Path $a "Idle.png") (Join-Path $dst "look-l.png") 32 0 16 16
  Crop (Join-Path $a "Idle.png") (Join-Path $dst "look-r.png") 48 0 16 16
  Crop (Join-Path $a "Walk.png") (Join-Path $dst "walk1.png") 0 16 16 16
  Crop (Join-Path $a "Walk.png") (Join-Path $dst "walk3.png") 0 48 16 16
  Crop (Join-Path $a "Item.png") (Join-Path $dst "item.png") 0 0 16 16
  Crop (Join-Path $a "Dead.png") (Join-Path $dst "dead.png") 0 0 16 16
  $names += $n
}
# The roster for the hero picker, as a JS module.
$js = "// Every hero in heroes/ (generated by src/heroes.ps1).`nexport const ROSTER = [" + (($names | ForEach-Object { '"' + $_ + '"' }) -join ", ") + "];`n"
[System.IO.File]::WriteAllText((Join-Path (Split-Path -Parent $here) "roster.js"), $js, (New-Object System.Text.UTF8Encoding $false))
Copy-Item (Join-Path $Pack "LICENSE.txt") (Join-Path $out "LICENSE-NinjaAdventure.txt") -Force
"heroes: $($names.Count)"
